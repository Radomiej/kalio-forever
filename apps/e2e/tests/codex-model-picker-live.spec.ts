import { expect, test } from '@playwright/test';
import { resolve } from 'node:path';

test.skip(process.env['KALIO_CODEX_PICKER_QA119'] !== '1', 'Explicit catalog/profile selection only; no generation');
test('discovers and selects exact Codex account model without sending a prompt', async ({ page }) => {
  const reportRun = process.env['KALIO_CODEX_PICKER_REPORT_RUN'] ?? '119';
  const model = process.env['KALIO_CODEX_PICKER_MODEL'] ?? 'gpt-6-luna';
  if (!/^\d+$/.test(reportRun) || !['gpt-6-luna', 'gpt-6-sol'].includes(model)) throw new Error('Invalid bounded picker test configuration');
  const optionName = new RegExp(`^Codex · ${model}`);
  const shot = (name: string) => resolve(__dirname, `../../../apps/e2e/outputs/qa-run-${reportRun}/assets/${name}.png`);
  const createdChats: string[] = [];
  page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/sessions') createdChats.push(request.url()); });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('http://localhost:5288/');
  await page.getByTestId('nav-talk').click();
  await expect(page.getByTestId('welcome-prompt-input')).toBeVisible();
  console.log((await page.locator('body').ariaSnapshot()).slice(-2200));
  await page.getByRole('button', { name: 'Recheck Codex models', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Recheck Codex models', exact: true })).toBeEnabled();
  const input = page.getByRole('combobox', { name: 'Provider and model', exact: true });
  await input.fill('Codex · gpt-');
  await expect(page.getByRole('option', { name: optionName })).toBeVisible();
  await expect(page.getByRole('option', { name: /^Codex · gpt-5\.4/ })).toHaveCount(0);
  await expect(page.getByRole('option', { name: /^Codex · gpt-5\.3/ })).toHaveCount(0);
  await page.screenshot({ path: shot('codex-catalog') });
  const request = page.waitForRequest(r => r.url().endsWith('/api/runtime/profiles/codex/resolve') && r.method() === 'POST');
  const response = page.waitForResponse(r => r.url().endsWith('/api/runtime/profiles/codex/resolve') && r.request().method() === 'POST');
  await page.getByRole('option', { name: optionName }).click();
  expect((await request).postDataJSON()).toEqual({ authProfileId: 'chatgpt-default', model });
  const resolved = await response;
  expect(resolved.ok()).toBe(true);
  expect(await resolved.json()).toMatchObject({ kind: 'codex-app-server', authProfileId: 'chatgpt-default', model, approvalMode: 'kalio_strict' });
  await expect(input).toHaveValue(`Codex · ${model}`);
  await expect(page.getByTestId('welcome-prompt-input')).toHaveValue('');
  await page.getByTestId('welcome-prompt-input').fill('Unsent QA launch readiness draft. Do not execute.');
  await expect(page.getByTestId('welcome-run-prompt')).toBeEnabled();
  await page.screenshot({ path: shot('codex-selected') });
  await page.getByTestId('welcome-prompt-input').fill('');
  expect(createdChats).toEqual([]);
});
