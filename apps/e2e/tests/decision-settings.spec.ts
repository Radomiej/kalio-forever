import { expect, test } from '@playwright/test';
import type { Credential, DecisionSettings, HitlConfig } from '@kalio/types';
import { API_BASE, ensureEnvMockProvider, expectComposerEnabled, getComposerSendButton, selectSession } from './helpers/test-config';
import { startDecisionFixture } from './helpers/decision-fixture';

test('Providers and Decision Settings save, reload and enable HITL with a local Decisions server', async ({ page, request }, testInfo) => {
  test.setTimeout(90_000);
  let createdSession: string | undefined;
  const decisionResponse = await request.get(`${API_BASE}/decision/config`);
  expect(decisionResponse.ok()).toBeTruthy();
  const previousDecision = await decisionResponse.json() as DecisionSettings;
  const hitlResponse = await request.get(`${API_BASE}/hitl/config`);
  expect(hitlResponse.ok()).toBeTruthy();
  const previousHitl = await hitlResponse.json() as HitlConfig;
  const fixture = await startDecisionFixture();
  let createdCredential: string | undefined;
  try {
    await page.goto('/');
    await page.getByTestId('nav-settings').click();
    await expect(page.getByTestId('settings-tab-llm')).toHaveText('Providers');
    await page.getByTestId('settings-tab-llm').click();
    await page.getByLabel('Decision credential name').fill('TypeSafe E2E fixture');
    await page.getByLabel('Decision API key').fill('test-only-key-not-a-real-secret');
    await page.getByRole('button', { name: 'Add Decision credential' }).click();
    await expect(page.getByText('TypeSafe E2E fixture (typesafe)')).toBeVisible();
    await expect(page.getByLabel('Decision API key')).toHaveValue('');
    const credentials = await (await request.get(`${API_BASE}/credentials`)).json() as Credential[];
    createdCredential = credentials.find((item) => item.name === 'TypeSafe E2E fixture')?.id;
    expect(createdCredential).toBeTruthy();
    expect(JSON.stringify(credentials)).not.toContain('test-only-key');
    await page.getByTestId('settings-tab-runtime').click();
    await page.getByRole('button', { name: 'Decision Settings', exact: true }).click();
    const panel = page.getByTestId('decision-settings-panel');
    await expect(panel).toBeVisible();
    await page.getByLabel('Decision provider', { exact: true }).selectOption('typesafe');
    await expect(page.getByLabel('Decision model')).toHaveValue('jev-1.13.0');
    await expect(page.getByLabel('Decision credential', { exact: true }).locator(`option[value="${createdCredential}"]`)).toHaveCount(1);
    await page.getByLabel('Decision provider', { exact: true }).selectOption('custom');
    await page.getByLabel('Decision model').fill('local-decision-fixture');
    await page.getByLabel('Decision endpoint').fill(fixture.endpoint);
    await page.getByRole('button', { name: 'Save Decision Settings' }).click();
    await expect(page.getByText('Decision Settings saved.')).toBeVisible();
    const configured = await (await request.get(`${API_BASE}/decision/config`)).json() as DecisionSettings;
    expect(configured).toEqual({ provider: 'custom', model: 'local-decision-fixture', credentialId: null, endpoint: fixture.endpoint });
    await page.screenshot({ path: testInfo.outputPath('decision-desktop.png') });
    await page.getByTestId('settings-tab-hitl').click();
    await page.getByRole('radio', { name: 'Jev', exact: true }).check();
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await expect.poll(async () => (await (await request.get(`${API_BASE}/hitl/config`)).json() as HitlConfig).mode).toBe('jev');
    await page.getByRole('button', { name: 'Configure Decision Settings' }).click();
    await expect(panel).toBeVisible();
    await expect(page.getByLabel('Decision model')).toHaveValue('local-decision-fixture');
    await page.reload();
    await page.getByTestId('nav-settings').click();
    await page.getByTestId('settings-tab-runtime').click();
    const decisionButton = page.getByRole('button', { name: 'Decision Settings', exact: true });
    await decisionButton.focus();
    await page.keyboard.press('Enter');
    await expect(page.getByLabel('Decision endpoint')).toHaveValue(fixture.endpoint);
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.getByRole('button', { name: 'Save Decision Settings' })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('decision-mobile.png') });
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.getByTestId('settings-close').click();
    await ensureEnvMockProvider(request);
    const title = 'Decision HITL ' + Date.now();
    const sessionResponse = await request.post(API_BASE + '/sessions', { data: { title, personaId: 'designer' } });
    expect(sessionResponse.ok()).toBeTruthy();
    const session = await sessionResponse.json() as { id: string };
    createdSession = session.id;
    await page.getByTestId('nav-talk').click();
    await selectSession(page, session.id, title);
    const composer = await expectComposerEnabled(page, 10_000);
    await composer.fill('[[mock:tool:vfs_write:no-arg-progress]] Use exactly the vfs_write tool and nothing else.');
    await (await getComposerSendButton(page)).click();
    await expect.poll(async () => fixture.requestCount).toBe(1);
    await expect.poll(async () => {
      const result = await request.get(API_BASE + '/sessions/' + session.id + '/vfs/read?path=e2e%2Fmock-tool-trigger.txt');
      return result.ok() ? (await result.json() as { content: string }).content : null;
    }, { timeout: 15_000 }).toBe('mock-trigger-confirmation');
    await expect(page.getByTestId('confirmation-confirm-btn')).toHaveCount(0);

  } finally {
    if (createdSession) expect((await request.delete(API_BASE + '/sessions/' + createdSession)).ok()).toBeTruthy();
    expect((await request.put(`${API_BASE}/hitl/config`, { data: previousHitl })).ok()).toBeTruthy();
    expect((await request.put(`${API_BASE}/decision/config`, { data: previousDecision })).ok()).toBeTruthy();
    if (createdCredential) expect((await request.delete(`${API_BASE}/credentials/${createdCredential}`)).ok()).toBeTruthy();
    await fixture.close();
  }
});
